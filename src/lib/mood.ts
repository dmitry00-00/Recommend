/** Что понято из запроса. Пустое `understood` — не понято ничего: такому запросу честнее ответить поиском по названию. */
export function parseMood(text: string, now = new Date()): MoodQuery {
  const t = ` ${norm(text).replace(/[«»"“”„]/g, '"').replace(/\s+/g, ' ')} `;
  const q: MoodQuery = { registers: {}, words: {}, understood: [] };
  // «не …», «без …», «только не …» — следующее слово или два с минусом
  const negated: [number, number][] = [];
  for (const m of t.matchAll(/(?:^|\s)(?:не|без|никаких|никакой|никакого)\s+(?:слишком\s+|сильно\s+|очень\s+)?(\S+(?:\s+\S+)?)/g)) negated.push([m.index! + m[0].length - m[1].length, m.index! + m[0].length]);
  const signAt = (at: number): 1 | -1 => (negated.some(([a, b]) => at >= a && at < b) ? -1 : 1);
  for (const r of RULES) {
    const re = new RegExp(`(?<=[\\s"(/,.!?-])${r.re.source}`, 'g');
    const m = re.exec(t);
    if (!m) continue;
    const sign = signAt(m.index);
    r.apply(q, sign);
    // у силы и «скучного» минус — это другая подпись, а не «не …»
    const flip: Record<string, string> = { 'на подумать': 'полегче', 'полегче': 'на подумать', 'захватывающее': 'захватывающее' };
    const label = sign > 0 ? r.label : flip[r.label] ?? `не ${r.label}`;
    if (!q.understood.includes(label)) q.understood.push(label);
  }
  // образец: «по типу X», «типа X», «как X», «вроде X», «похожее на X» — до запятой или конца
  const like = /(?:по типу|в стиле|типа|вроде|похож\S* на|как в|как)\s+"?([^",.!?]{2,60})/.exec(t);
  if (like && !/^(можно|нибудь|то|будто|обычно|раньше)\b/.test(like[1].trim())) { q.like = like[1].trim(); q.understood.push(`похожее на «${q.like}»`); }
  // фильм или сериал — только если назван один
  const film = /(?<=\s)(фильм|кино|мультфильм)/.test(t), series = /(?<=\s)(сериал|дорам|мини-?сериал)/.test(t);
  if (series && !film) { q.kind = 'series'; q.understood.push('сериал'); }
  else if (film && !series && !/фильм или|или фильм/.test(t)) q.kind = 'film';
  // свежесть
  const year = now.getFullYear();
  if (/(?<=\s)(свеж|новинк|новое|новый|новые|недавн|последн\S* год)/.test(t)) { q.fromYear = year - 2; q.understood.push('свежее'); }
  else if (/(?<=\s)(стар(ое|ый|ые|ого)|старин|ретро|черно-?бел)/.test(t)) { q.toYear = 1990; q.understood.push('старое'); }
  const decade = /(\d0)-?[хе]/.exec(t);
  if (decade) { const d = Number(decade[1]); const from = d >= 20 && d <= 90 ? 1900 + d : 2000 + d; q.fromYear = from; q.toYear = from + 9; q.understood.push(`${decade[1]}-е`); }
  // длина
  if (/(коротк|недлинн|не долг|полтора часа|1[:.]30|1[:.]40|до двух час)/.test(t)) { q.maxMinutes = 110; q.understood.push('недлинное'); }
  // страна
  for (const [re, name, label] of COUNTRY) if (new RegExp(`(?<=\\s)${re.source}`).test(t)) { (q.countries ??= []).push(name); q.understood.push(label); }
  // «про X» без словаря — слова темы как есть (основа — первые пять букв)
  for (const m of t.matchAll(/(?<=\s)(?:про|о|об)\s+([а-я]{4,})/g)) {
    const stem = m[1].slice(0, Math.min(5, m[1].length - 1));
    if (!Object.keys(q.words).flatMap((k) => k.split('|')).some((w) => stem.startsWith(w) || w.startsWith(stem))) { q.words[stem] = (q.words[stem] ?? 0) + 1; q.understood.push(`про ${m[1]}`); }
  }
  return q;
}

export interface MoodTarget { work: WorkCard; what: string }

/** Насколько кандидат подходит под запрос: 0 — мимо (или отсеян фильтром), выше — лучше; без единого сигнала — 0. */
export function moodFit(q: MoodQuery, c: MoodTarget): number {
  const w = c.work;
  if (q.kind === 'series' && w.type !== 'series') return 0;
  if (q.kind === 'film' && w.type === 'series') return 0;
  if (q.fromYear && w.year && w.year < q.fromYear) return 0;
  if (q.toYear && w.year && w.year > q.toYear) return 0;
  if (q.maxMinutes && w.durationMinutes && w.durationMinutes > q.maxMinutes) return 0;
  const horror = w.warnings.includes('Хоррор-образы') || w.barriers.includes('Хоррор-образы');
  if (q.horror === -1 && horror) return 0;
  // «не надо» только вычитает: иначе «не грустное» размывало бы долю остального
  let score = 0, max = 0;
  for (const [r, weight] of Object.entries(q.registers) as [Register, number][]) {
    if (weight > 0) max += weight;
    if (w.registers?.includes(r)) score += weight;
  }
  if (q.horror === 1) { max += 1; if (horror) score += 1; }
  const text = norm(`${c.what} ${w.title}`);
  for (const [stems, weight] of Object.entries(q.words)) {
    if (weight > 0) max += weight;
    if (new RegExp(`(?:^|[^а-я])(?:${stems})`).test(text)) score += weight;
  }
  if (q.countries?.length) {
    max += 0.5;
    const ru = (w.countries ?? []).map(countryRu);
    if (q.countries.some((x) => ru.includes(x))) score += 0.5;
  }
  if (q.niche) { max += 1; if (w.isNicheMasterpiece) score += 1; }
  return max ? Math.max(0, score / max) : 0;
}
