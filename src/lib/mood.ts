// Подбор по настроению словами (ЗП-16, 07.10): «что-то тихое про семью, не грустное» → что понято и как это
// мерить на кандидате. Модели во время запроса нет (сервер её не держит, а локальная — на Mac владельца), поэтому —
// словарь. Формулировки взяты из живых просьб «посоветуйте» в Telegram (ТВ-12а, .cache/tg-asks): настроение
// («поплакать», «не скучный»), сила («на подумать», «не сильно сложный»), жанр, повод («на вечер», «осенний»),
// тема («про подростков»), свежесть, страна, длина, образец («по типу „Иллюзии обмана“»).
// Жанров у карточки нет: жанр — это регистр (ось вкуса, src/lib/registers.ts), предупреждения («Хоррор-образы») и
// слова строки «что вещь делает» — в ней жанр почти всегда назван. «Не …» и «без …» переворачивают сигнал.
import type { Energy, Register, WorkCard } from '@/types/tmdf';
import { countryRu } from './countries';

export interface MoodQuery {
  /** регистр → вес (отрицательный — «не надо») */
  registers: Partial<Record<Register, number>>;
  /** слова строки «что делает» и названия: группа основ через `|` → вес (отрицательный — «не надо»). Группа
   *  засчитывается целиком, если совпала любая её основа: «семья» — это отец, или мать, или сын, а не всё сразу */
  words: Record<string, number>;
  /** хоррор-образы: 1 — хочется, -1 — без них */
  horror?: 1 | -1;
  energy?: Energy;
  kind?: 'film' | 'series';
  /** годы: свежее — от, старое — до */
  fromYear?: number;
  toYear?: number;
  /** до скольких минут (фильм) */
  maxMinutes?: number;
  /** страна по-русски, как её пишет `countryRu` */
  countries?: string[];
  /** культовое — то, о чём больше всего разборов; нишевое — признанное, но малоизвестное */
  canon?: true;
  niche?: true;
  /** образец: «по типу …», «как …» — название, которое потом ищется в справочнике */
  like?: string;
  /** что понято — подписями для человека, в порядке запроса */
  understood: string[];
}

const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е');

interface Rule { re: RegExp; label: string; apply: (q: MoodQuery, sign: 1 | -1) => void }
const reg = (r: Register, w: number) => (q: MoodQuery, sign: 1 | -1) => { q.registers[r] = (q.registers[r] ?? 0) + sign * w; };
const words = (list: string[], w = 1) => (q: MoodQuery, sign: 1 | -1) => { const k = list.join('|'); q.words[k] = (q.words[k] ?? 0) + sign * w; };
const all = (...fs: ((q: MoodQuery, sign: 1 | -1) => void)[]) => (q: MoodQuery, sign: 1 | -1) => { for (const f of fs) f(q, sign); };

