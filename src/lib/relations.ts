// Узлы связей (Ж1), которые не цикл и не франшиза, а перечень: «100 величайших фильмов XXI века по
// версии BBC», «Список полнометражных мультфильмов Pixar», «фильмы студии Walt Disney Animation».
// В Wikidata фильм бывает «частью» (P179) такого перечня, и через него десятки несвязанных фильмов
// склеивались в одну вселенную: на 01.10 «Левиафан» оказался во «Вселенной DC» (234 узла) и пришёл в
// ленту слотом «дальше во вселенной». Общее для сборки (tools/relations-lib.mts) и приложения.
const LIST = /^(?:список|перечень|(?:\d+|сто)\s+(?:лучш|величайш|главн|важн|фильм|мультфильм|книг)|лучш|величайш|полнометражн\p{L}*\s+(?:фильм|мультфильм)|(?:фильмы|мультфильмы)\s+(?:студии|компании|производства|по\s+версии))|по\s+версии|\blist\s+of\b|\bfilms?\s+by\b|\bfilmography\b|фильмограф/iu;

export const listLike = (title?: string): boolean => Boolean(title && LIST.test(title.trim()));
